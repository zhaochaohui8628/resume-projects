def _allocate(text: str, fixes: list, qid: str) -> list[dict]:
    used = []
    ents = []
    for typ, frag in fixes:
        chosen = None
        for m in re.finditer(re.escape(frag), text):
            s, e = m.start(), m.end()
            if any(s < ue and us < e for us, ue in used):
                continue
            chosen = (s, e)
            break
        if chosen is None:
            raise SystemExit(f"[error] {qid} 片段无可用位置: {frag!r} in {text!r} used={used}")
        used.append(chosen)
        ents.append({"type": typ, "start": chosen[0], "end": chosen[1]})
    return ents


