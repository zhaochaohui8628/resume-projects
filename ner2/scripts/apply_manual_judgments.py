# ============ 落盘逻辑 ============


def _allocate(text: str, fixes: list, qid: str) -> list[dict]:
    """片段 -> 字符偏移：计数分配 + 重叠跳过（同片段多次出现按序取位）。"""
    import re
    used = []
    ents = []
    for typ, frag in fixes:
        chosen = None
        for m in re.finditer(re.escape(frag), text):
            s, e = m.start(), m.end()
            if any(s < ue and us < e for us, ue in used):
                continue
            chosen = (s, e)
            break
        if chosen is None:
            raise SystemExit(f"[error] {qid} 片段无可用位置: {frag!r} in {text!r} used={used}")
        used.append(chosen)
        ents.append({"type": typ, "start": chosen[0], "end": chosen[1]})
    return ents


def main():
    rows = [json.loads(l) for l in open(POOL, encoding="utf-8")]
    pool = {r["qid"]: r for r in rows}
    out = []
    n_fix = n_drop = n_keep = 0
    for qid, r in pool.items():
        text = r["text"]
        if qid in FIXES:
            fixes, reason = FIXES[qid]
            ents = _allocate(text, fixes, qid)
            out.append({"qid": qid, "text": text, "verdict": "fix",
                        "entities": ents, "issues": [reason], "reason": reason,
                        "raw": {"verdict": "fix", "entities": ents}})
            n_fix += 1
        elif qid in DROPS:
            out.append({"qid": qid, "text": text, "verdict": "drop",
                        "entities": [], "issues": [DROPS[qid]], "reason": DROPS[qid],
                        "raw": {"verdict": "drop", "entities": []}})
            n_drop += 1
        else:
            out.append({"qid": qid, "text": text, "verdict": "keep",
                        "entities": [{"type": e["type"], "start": e["start"], "end": e["end"]}
                                     for e in r["entities"]],
                        "issues": [], "reason": "规则标签正确",
                        "raw": {"verdict": "keep"}})
            n_keep += 1
    with open(JUDGMENTS, "w", encoding="utf-8") as f:
        for j in out:
            f.write(json.dumps(j, ensure_ascii=False) + "\n")
    print(f"judgments: keep {n_keep} / fix {n_fix} / drop {n_drop} / total {len(out)}")
    print(f"-> {JUDGMENTS}")


if __name__ == "__main__":
    main()
